"""规则式规划器的「词表与权重」。

所有可调参数集中在这里，好处是：调准确率时只改数据、不动逻辑，
而且每个权重为什么是那个值，都能在博文里讲清楚。

打分有五路来源
-------------
1. **trigger**：意图关键词，按「出现次数 × 位置权重」累加
2. **object**：正则描述的宾语模式（比关键词更精确，权重也更高）
3. **negative**：负分，用来排除「字面像但其实不是」的情况
   （如「天气之子好看吗」不该触发查天气）
4. **context**：上下文延续，上一步调了 A 工具、当前句又在说图表，就给图表加分
5. **diversity**：命中类别数 ≥2 时的小额奖励，区分「只说天气」和「天气+画图」
"""

