def render(text: str, scale: int = 1, fill: str = "#") -> tuple[str, int]:
    """返回 (艺术字, 无法渲染的字符数)。"""
    scale = max(1, min(int(scale), 3))
    fill_char = (fill or "#")[0]
    normalized = str(text).upper()
    missing = 0

    # 逐行拼接：先算每一行，再把整行横向重复 scale 次、纵向重复 scale 次
    rows = ["" for _ in range(_ROW)]
    for char in normalized:
        # 归一化会把英文转小写，点阵表只有大写，所以退一步按大写再查一次
        glyph = _GLYPHS.get(char) or _GLYPHS.get(char.upper())
        if glyph is None:
            glyph = _GLYPHS["?"]
            missing += 1
        for index in range(_ROW):
            rows[index] += glyph[index] + "."

    lines: list[str] = []
    for row in rows:
        expanded = "".join(fill_char if cell == "#" else " " for cell in row)
        for _ in range(scale):
            lines.append(expanded)
    return "\n".join(lines), missing


def run(args: dict) -> ToolResult:
    text = str(args.get("text", "") or "").strip()
    if not text:
        return ToolResult.failure("没给要转换的文字", hint="例如 text=HELLO")
    if len(text) > 24:
        text = text[:24]

    try:
        scale = int(args.get("scale", 1))
    except (TypeError, ValueError):
        scale = 1
    fill = str(args.get("fill", "#") or "#")

    art, missing = render(text, scale, fill)

    note = f"（{missing} 个字符不在点阵表里，已用 ? 占位）" if missing else ""
    target = output_path("ascii", ".txt")
    try:
        target.write_text(art, encoding="utf-8")
    except OSError:
        target = None  # type: ignore[assignment]

    artifacts = []
    if target is not None:
        artifacts.append(Artifact(kind="text", path=str(target), mime="text/plain", caption=text))

    return ToolResult.success(
        f"艺术字做好了{note}\n\n{art}",
        data={
            "art": art,
            "width": max(len(line) for line in art.splitlines()),
            "height": len(art.splitlines()),
            "missing_chars": missing,
            "path": str(target) if target else "",
        },
        artifacts=artifacts,
    )


if __name__ == "__main__":
    print(run({"text": "HI"}).data["art"])
